from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

router = Router()

EXCEL_GUIDE = """\
📊 <b>Как читать Excel-экспорт</b>

<b>Лист «news_cards»</b> — все обработанные новости.
Главные колонки:
• Дата — публикация в Telegram
• Источник — название канала
• Заголовок — первая содержательная строка
• Резюме для сайта — краткий пересказ от ИИ
• Темы — тематические разделы
• Релевантность — балл 0–100
• Уровень — high / medium / low / irrelevant
• Статус проверки — auto / needs_review / approved / rejected

<b>Лист «trend_cases»</b> — структурированные кейсы для аналитиков.
Колонки:
• Тренд — название тренда
• Кейс — конкретное событие
• Компания — главная организация
• Описание — что произошло
• Как работает — техническая суть
• Ценность — почему важно
• Рынок — Россия / Мир / Россия и мир

<b>Лист «trends»</b> — база знаний трендов.
Каждая строка — отдельный тренд с количеством кейсов.

<b>Лист «review»</b> — кейсы для ручной проверки.
Отфильтрованы по статусу draft, отсортированы по релевантности.

<b>Лист «raw_posts»</b> — исходные посты как есть из Telegram.
Для отладки и перепроверки.

<b>🎨 Цветовая кодировка строк:</b>
🟡 <b>Жёлтый</b> — рекламный пост (есть #реклама, erid, ИНН и т.п.)
   Требует особого внимания перед публикацией.

🟢 <b>Зелёный</b> — высокая релевантность (score ≥ 60)
   Приоритет для дайджеста.

⬜ <b>Светло-серый</b> — низкая или нулевая релевантность
   Скорее всего не подходит для дайджеста.

⚪ <b>Белый</b> — средняя релевантность, требует проверки.

Приоритет: жёлтый &gt; зелёный &gt; остальное.

<b>📋 Статусы проверки:</b>
• <code>auto</code> — обработано автоматически, можно доверять
• <code>needs_review</code> — требует ручной проверки
• <code>approved</code> — одобрено редактором
• <code>rejected</code> — отклонено

<b>🔍 Поиск через бота:</b>
/search текст — поиск по содержимому
/company название — кейсы по компании
/topic тема — кейсы по теме
/trends — список всех трендов\
"""


@router.message(Command("excel_guide"))
async def cmd_excel_guide(message: Message) -> None:
    await message.answer(EXCEL_GUIDE)

    for company in KNOWN_COMPANIES:
        if company not in seen:
            pos = text_lower.find(company.lower())
            if pos != -1:
                positions.append((pos, company))
                seen.add(company)
    positions.sort(key=lambda x: x[0])
    return [company for _, company in positions]
